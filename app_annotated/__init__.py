# 【文件定位】alun/app/__init__.py —— Python 包 alun.app 的“包初始化文件”
#
# 一、这个文件负责什么：
#     1. 告诉 Python：“app 目录是一个可导入的包（package）”，而不是普通文件夹；
#     2. 规定第一次 import alun.app 时执行哪些初始化语句。本文件只放了两项内容：
#        模块文档字符串和包级版本号 __version__，没有任何业务逻辑或副作用；
#     3. 为整个后端提供一个轻量的包入口和元信息位置。真正的 FastAPI 应用实例、
#        数据库初始化、路由注册都在同目录的 main.py 中完成，不在本文件里。
#
# 二、它在整个应用中的位置：
#     - 项目启动命令是 `uvicorn alun.app.main:app`，导入链路为：
#       alun 包 → alun.app 包（执行本文件）→ alun.app.main 模块；
#     - 因此本文件是整个 app 子包最早被执行的代码之一，但它刻意保持“极薄”：
#       不 import main、config、db 等上层模块，从源头避免循环导入和启动顺序问题；
#     - app 下各模块通过 `from . import xxx` 或 `from .config import ...` 相互引用；
#       每次导入子模块时，Python 都会先确保本包已初始化，然后复用 sys.modules
#       中缓存的包对象，不会重复执行本文件。
#
# 三、主要调用关系（谁读取这里的名字）：
#     - Python 的导入系统：读取并缓存模块文档字符串 `__doc__` 和 `__version__`；
#     - 运维/发布脚本或第三方工具可能读取 `alun.app.__version__` 做版本展示或核对；
#     - 当前项目源码中没有其它模块 import 这个 __version__。应用实际展示和
#       FastAPI 构造参数使用的是 app/config.py 里的 APP_VERSION（当前为 "2.0.0"），
#       所以这里的 "1.0.0" 是包级元信息，二者不要混为一谈。
#
# 四、阅读提示：
#     - 本文件没有 import、类、函数、分支、循环、异常处理或返回值；
#       下面仍逐段解释已有的文档字符串、空行和版本赋值，帮助初学者理解包机制；
#     - app_annotated 是供学习阅读的副本；生产运行时加载的仍是 alun/app/__init__.py。
# =============================================================================
# 【原文件第 1 行｜模块文档字符串】
# 下面这个三引号字符串是模块的第一条语句，会被 Python 自动保存到模块属性 __doc__
# 中，可用 help(alun.app) 或 alun.app.__doc__ 查看。它解释了本包的用途：
# “A论”是项目名，“论文导读智能体”是产品定位。字符串内容必须逐字保留，不能改写。
"""A论 · 论文导读智能体。"""

# 【原文件第 2 行｜空行】
# 这里保留原文件中的空行，用来分隔“文档字符串”和“版本号赋值”两个逻辑部分。
# 空行不参与执行，也不会改变文档字符串作为“模块第一条语句”的身份。

# 【原文件第 3 行｜包级版本号赋值】
# 这是本文件唯一的可执行语句。`__version__` 是 Python 社区广泛约定的版本属性名：
# 双下划线开头和结尾表示“由约定/解释器使用的特殊名字”，不是普通业务变量。
# 赋值过程：等号右侧先求值为字符串 "1.0.0"（语义化版本：主版本.次版本.修订号），
# 再把该字符串绑定到当前包对象的 __version__ 属性上；没有函数调用，也没有 I/O。
# 这里使用双引号且内容与缩进均保持原样；不要为了“统一风格”改成单引号或其它版本号，
# 否则会改变可观察到的包元信息。版本升级时应由发布流程统一评估并同步相关配置。
__version__ = "1.0.0"
# 【执行结果】
# 执行完本文件后，alun.app 包对象上会多出两个可读属性：
#   - __doc__     = "A论 · 论文导读智能体。"（由上面的文档字符串提供）；
#   - __version__ = "1.0.0"（由上面的赋值提供）。
# 因为没有定义 __all__，执行 `from alun.app import *` 时不会导出以下划线开头的
# __version__；需要使用版本号时应显式写 `import alun.app; alun.app.__version__`。
